-- ----------------------------------------------------------------------------
-- 1. Tabel data kunjungan
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.kunjungan_bulanan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tahun INT NOT NULL,
  bulan INT NOT NULL CHECK (bulan BETWEEN 1 AND 12),
  periode_label TEXT NOT NULL,
  nama_poli TEXT NOT NULL,
  baru_l INT NOT NULL DEFAULT 0 CHECK (baru_l >= 0),
  baru_p INT NOT NULL DEFAULT 0 CHECK (baru_p >= 0),
  lama_l INT NOT NULL DEFAULT 0 CHECK (lama_l >= 0),
  lama_p INT NOT NULL DEFAULT 0 CHECK (lama_p >= 0),
  jumlah_l INT NOT NULL DEFAULT 0 CHECK (jumlah_l >= 0),
  jumlah_p INT NOT NULL DEFAULT 0 CHECK (jumlah_p >= 0),
  total_kunjungan INT GENERATED ALWAYS AS (jumlah_l + jumlah_p) STORED,
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  updated_by UUID REFERENCES auth.users(id),

  -- Mencegah duplikasi data poli pada bulan dan tahun yang sama.
  CONSTRAINT unique_periode_poli UNIQUE (tahun, bulan, nama_poli)
);

CREATE INDEX IF NOT EXISTS idx_kunjungan_periode
  ON public.kunjungan_bulanan (tahun, bulan);

CREATE INDEX IF NOT EXISTS idx_kunjungan_poli
  ON public.kunjungan_bulanan (nama_poli);

-- ----------------------------------------------------------------------------
-- 2. Tabel total kunjungan online per periode (bukan per poli)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.kunjungan_online_bulanan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tahun INT NOT NULL,
  bulan INT NOT NULL CHECK (bulan BETWEEN 1 AND 12),
  jumlah_online INT NOT NULL DEFAULT 0 CHECK (jumlah_online >= 0),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  updated_by UUID REFERENCES auth.users(id),

  -- Satu total online per bulan/tahun.
  CONSTRAINT unique_periode_online UNIQUE (tahun, bulan)
);

CREATE INDEX IF NOT EXISTS idx_kunjungan_online_periode
  ON public.kunjungan_online_bulanan (tahun, bulan);

-- ----------------------------------------------------------------------------
-- 3. Trigger updated_at otomatis
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_kunjungan_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_kunjungan_updated_at ON public.kunjungan_bulanan;

CREATE TRIGGER trg_kunjungan_updated_at
BEFORE UPDATE ON public.kunjungan_bulanan
FOR EACH ROW
EXECUTE FUNCTION public.set_kunjungan_updated_at();

DROP TRIGGER IF EXISTS trg_kunjungan_online_updated_at ON public.kunjungan_online_bulanan;

CREATE TRIGGER trg_kunjungan_online_updated_at
BEFORE UPDATE ON public.kunjungan_online_bulanan
FOR EACH ROW
EXECUTE FUNCTION public.set_kunjungan_updated_at();

-- ----------------------------------------------------------------------------
-- 4. Hak akses tabel (dikombinasikan dengan RLS di bawah)
-- ----------------------------------------------------------------------------
GRANT SELECT ON public.kunjungan_bulanan TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.kunjungan_bulanan TO authenticated;
GRANT SELECT ON public.kunjungan_online_bulanan TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.kunjungan_online_bulanan TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- ----------------------------------------------------------------------------
-- 5. Row Level Security
-- ----------------------------------------------------------------------------
ALTER TABLE public.kunjungan_bulanan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kunjungan_online_bulanan ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Publik dapat melihat data kunjungan" ON public.kunjungan_bulanan;
DROP POLICY IF EXISTS "Admin dapat menambah data" ON public.kunjungan_bulanan;
DROP POLICY IF EXISTS "Admin dapat mengubah data" ON public.kunjungan_bulanan;
DROP POLICY IF EXISTS "Admin dapat menghapus data" ON public.kunjungan_bulanan;

-- Pengunjung (anon) dan admin dapat melihat semua data.
CREATE POLICY "Publik dapat melihat data kunjungan"
ON public.kunjungan_bulanan
FOR SELECT
TO anon, authenticated
USING (true);

-- Hanya pengguna terautentikasi (admin) yang dapat menulis data.
CREATE POLICY "Admin dapat menambah data"
ON public.kunjungan_bulanan
FOR INSERT
TO authenticated
WITH CHECK (true);

CREATE POLICY "Admin dapat mengubah data"
ON public.kunjungan_bulanan
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);

CREATE POLICY "Admin dapat menghapus data"
ON public.kunjungan_bulanan
FOR DELETE
TO authenticated
USING (true);

DROP POLICY IF EXISTS "Publik dapat melihat data online" ON public.kunjungan_online_bulanan;
DROP POLICY IF EXISTS "Admin dapat menambah data online" ON public.kunjungan_online_bulanan;
DROP POLICY IF EXISTS "Admin dapat mengubah data online" ON public.kunjungan_online_bulanan;
DROP POLICY IF EXISTS "Admin dapat menghapus data online" ON public.kunjungan_online_bulanan;

CREATE POLICY "Publik dapat melihat data online"
ON public.kunjungan_online_bulanan
FOR SELECT
TO anon, authenticated
USING (true);

CREATE POLICY "Admin dapat menambah data online"
ON public.kunjungan_online_bulanan
FOR INSERT
TO authenticated
WITH CHECK (true);

CREATE POLICY "Admin dapat mengubah data online"
ON public.kunjungan_online_bulanan
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);

CREATE POLICY "Admin dapat menghapus data online"
ON public.kunjungan_online_bulanan
FOR DELETE
TO authenticated
USING (true);

