-- ============================================================================
-- Migrasi: total Kunjungan Online per periode
--
-- Jalankan file ini SEKALI jika database sudah dibuat dengan schema.sql
-- versi sebelumnya. Project baru cukup menjalankan schema.sql.
--
-- Fitur lama menyimpan angka online per poli pada kolom
-- kunjungan_bulanan.pendaftaran_online. Kolom itu tidak lagi dipakai karena
-- kunjungan online sekarang dicatat sebagai satu total per bulan/tahun.
-- ============================================================================

-- 1. Hapus kolom lama (opsional, data online per poli tidak dipakai lagi).
ALTER TABLE public.kunjungan_bulanan
  DROP COLUMN IF EXISTS pendaftaran_online;

-- 2. Buat tabel total online per periode.
CREATE TABLE IF NOT EXISTS public.kunjungan_online_bulanan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tahun INT NOT NULL,
  bulan INT NOT NULL CHECK (bulan BETWEEN 1 AND 12),
  jumlah_online INT NOT NULL DEFAULT 0 CHECK (jumlah_online >= 0),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  updated_by UUID REFERENCES auth.users(id),
  CONSTRAINT unique_periode_online UNIQUE (tahun, bulan)
);

CREATE INDEX IF NOT EXISTS idx_kunjungan_online_periode
  ON public.kunjungan_online_bulanan (tahun, bulan);

-- 3. Trigger updated_at.
CREATE OR REPLACE FUNCTION public.set_kunjungan_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_kunjungan_online_updated_at ON public.kunjungan_online_bulanan;

CREATE TRIGGER trg_kunjungan_online_updated_at
BEFORE UPDATE ON public.kunjungan_online_bulanan
FOR EACH ROW
EXECUTE FUNCTION public.set_kunjungan_updated_at();

-- 4. Hak akses.
GRANT SELECT ON public.kunjungan_online_bulanan TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.kunjungan_online_bulanan TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- 5. Row Level Security.
ALTER TABLE public.kunjungan_online_bulanan ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Publik dapat melihat data online" ON public.kunjungan_online_bulanan;
DROP POLICY IF EXISTS "Admin dapat menambah data online" ON public.kunjungan_online_bulanan;
DROP POLICY IF EXISTS "Admin dapat mengubah data online" ON public.kunjungan_online_bulanan;
DROP POLICY IF EXISTS "Admin dapat menghapus data online" ON public.kunjungan_online_bulanan;

CREATE POLICY "Publik dapat melihat data online"
ON public.kunjungan_online_bulanan
FOR SELECT
TO anon, authenticated
USING (true);

CREATE POLICY "Admin dapat menambah data online"
ON public.kunjungan_online_bulanan
FOR INSERT
TO authenticated
WITH CHECK (true);

CREATE POLICY "Admin dapat mengubah data online"
ON public.kunjungan_online_bulanan
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);

CREATE POLICY "Admin dapat menghapus data online"
ON public.kunjungan_online_bulanan
FOR DELETE
TO authenticated
USING (true);
